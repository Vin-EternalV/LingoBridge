const BY_LOWERCASE = new Map(LANGUAGES.map((language) => [language.toLowerCase(), language]));

// Returns the list's exact spelling for a language name (any capitalisation), or null if it is not on the list.
const findLanguage = (value) => {
  if (typeof value !== 'string') return null;
  return BY_LOWERCASE.get(value.trim().toLowerCase()) || null;
};

